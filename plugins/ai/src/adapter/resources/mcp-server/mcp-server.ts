/** AI MCP server scaffolding and registry emission. */

import { type ScaffoldArtifact, textArtifact } from '@netscript/plugin/adapter';

/** Supported generated MCP server configuration; service references resolve at app startup. */
export type McpServerInput =
  | {
    readonly id: string;
    readonly transport: 'streamable-http' | 'stdio';
    readonly target: string;
    readonly authEnv?: string;
  }
  | {
    readonly id: string;
    readonly transport: 'service';
    readonly service: string;
    readonly path?: string;
    readonly protocol?: 'http' | 'https';
    readonly authEnv?: string;
  };

/** Emit one app-owned MCP server transport configuration, rejecting invalid input before writes. */
export function emitMcpServer(input: McpServerInput): ScaffoldArtifact {
  validateInput(input);
  const auth = input.authEnv
    ? `,\n  auth: { mode: 'api-token', token: Deno.env.get(${
      JSON.stringify(input.authEnv)
    }) ?? '' }`
    : '';
  const url = input.transport === 'service'
    ? `new URL(${JSON.stringify(input.path ?? '/mcp')}, getServiceUrl(${
      JSON.stringify(input.service)
    }, ${JSON.stringify(input.protocol ?? 'http')})).href`
    : input.transport === 'streamable-http'
    ? JSON.stringify(input.target)
    : '';
  const endpoint = input.transport === 'stdio'
    ? `kind: 'stdio',\n  command: ${JSON.stringify(input.target)}`
    : `kind: 'streamable-http',\n  url: ${url}${auth}`;
  const discovery = input.transport === 'service'
    ? `import { getServiceUrl } from '@netscript/sdk/discovery';\n`
    : '';
  return textArtifact(
    `ai/mcp/${input.id}.ts`,
    `/** MCP server ${JSON.stringify(input.id)}. Generated by plugin ai mcp add. */\n` +
      `import type { McpTransportConfig } from '@netscript/ai/mcp';\n${discovery}\n` +
      `export const config: McpTransportConfig = {\n  ${endpoint},\n` +
      `  serverId: ${JSON.stringify(input.id)},\n};\n`,
  );
}

function validateInput(input: McpServerInput): void {
  if (!/^[a-z][a-z0-9-]*$/.test(input.id)) {
    throw new TypeError(
      'MCP server id must start with a lowercase letter and use letters, digits or hyphens.',
    );
  }
  if (input.authEnv !== undefined && !input.authEnv.trim()) {
    throw new TypeError('--auth requires a nonempty environment variable name.');
  }
  if (input.transport === 'service') {
    if (!/^[a-zA-Z][a-zA-Z0-9-]*$/.test(input.service)) {
      throw new TypeError(
        '--service requires a logical service name using letters, digits or hyphens.',
      );
    }
    if (input.protocol !== undefined && input.protocol !== 'http' && input.protocol !== 'https') {
      throw new TypeError('--protocol must be http or https.');
    }
    validatePath(input.path ?? '/mcp');
  } else {
    if (!input.target.trim()) throw new TypeError('MCP transport target must not be empty.');
    if (input.transport === 'streamable-http') {
      let url: URL;
      try {
        url = new URL(input.target);
      } catch {
        throw new TypeError('--url requires an absolute HTTP or HTTPS URL.');
      }
      if (url.protocol !== 'http:' && url.protocol !== 'https:') {
        throw new TypeError('--url requires an absolute HTTP or HTTPS URL.');
      }
    }
  }
}

function validatePath(path: string): void {
  let decoded: string;
  try {
    decoded = decodeURIComponent(path);
  } catch {
    throw new TypeError('--path contains invalid percent encoding.');
  }
  if (
    !path.startsWith('/') || path.startsWith('//') || /[\\\s?#]/.test(decoded) ||
    [...decoded].some((char) => char.charCodeAt(0) < 32 || char.charCodeAt(0) === 127) ||
    /%2f|%5c/i.test(path) || decoded.split('/').some((part) => part === '.' || part === '..')
  ) {
    throw new TypeError(
      '--path must be an absolute path such as /mcp, without an origin, query, fragment or dot segments.',
    );
  }
}

/** Emit the MCP registry consumed by the app AI composition root. */
export function emitMcpRegistry(ids: readonly string[]): ScaffoldArtifact {
  const imports = ids.map((id, index) => `import { config as server${index} } from './${id}.ts';`);
  const servers = ids.map((_id, index) => `server${index}`).join(', ');
  return textArtifact(
    'ai/mcp/registry.ts',
    `/** MCP registry. Generated by the AI plugin CLI. */\n` +
      `import { createMcpTransportPool, registerMcpTools } from '@netscript/ai/mcp';\n` +
      `import type { AiToolRegistry } from '@netscript/ai/tools';\n` +
      `${imports.join('\n')}\n\n` +
      `export const MCP_SERVER_IDS = ${JSON.stringify(ids)} as const;\n` +
      `const pool = createMcpTransportPool({ servers: [${servers}] });\n\n` +
      `/** Connect configured MCP servers and surface their tools in the AI registry. */\n` +
      `export async function initializeMcpTools(tools: AiToolRegistry): Promise<void> {\n` +
      `  if (!MCP_SERVER_IDS.length) return;\n` +
      `  await registerMcpTools(tools, pool);\n` +
      `}\n`,
  );
}
