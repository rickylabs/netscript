/** Embed authoritative registry JSON as compact TypeScript without publish-time asset imports. */
const root = new URL('../', import.meta.url);
const target = new URL('src/registry/assets/registry.generated.ts', root);
const check = Deno.args.includes('--check');
const inputs = [
  { name: 'registryJson', type: 'Registry', path: 'registry.json' },
  { name: 'registrySchema', type: 'SchemaObject', path: 'src/registry/schemas/registry.json' },
  { name: 'itemSchema', type: 'SchemaObject', path: 'src/registry/schemas/registry-item.json' },
] as const;

const declarations: string[] = [];
for (const { name, type, path } of inputs) {
  const value: unknown = JSON.parse(await Deno.readTextFile(new URL(path, root)));
  const bytes = new TextEncoder().encode(JSON.stringify(value));
  const compressed = new Uint8Array(
    await new Response(
      new Blob([bytes]).stream().pipeThrough(new CompressionStream('gzip')),
    ).arrayBuffer(),
  );
  const encoded = btoa(Array.from(compressed, (byte) => String.fromCharCode(byte)).join(''));
  declarations.push(`export const ${name}: ${type} = JSON.parse(await new Response(
    new Blob([Uint8Array.from(atob(${JSON.stringify(encoded)}), (char) => char.charCodeAt(0))])
      .stream().pipeThrough(new DecompressionStream('gzip')),
  ).text());\n`);
}
const source = '// @generated by scripts/embed-registry-assets.ts\n' +
  '// Do not edit. Run `deno task registry:embed`. JSON sources remain authoritative.\n\n' +
  "import type { SchemaObject } from 'npm:ajv@8.20.0';\n" +
  "import type { Registry } from '../registry-contract.ts';\n\n" + declarations.join('\n');
const process = new Deno.Command(Deno.execPath(), {
  args: ['fmt', '--ext', 'ts', '-'],
  cwd: root,
  stdin: 'piped',
  stdout: 'piped',
  stderr: 'piped',
}).spawn();
const writer = process.stdin.getWriter();
await writer.write(new TextEncoder().encode(source));
await writer.close();
const result = await process.output();
if (result.code !== 0) throw new Error(new TextDecoder().decode(result.stderr));
const content = new TextDecoder().decode(result.stdout);
if (check) {
  if (await Deno.readTextFile(target).catch(() => undefined) !== content) {
    throw new Error('Stale embedded registry assets: src/registry/assets/registry.generated.ts');
  }
} else {
  await Deno.mkdir(new URL('./', target), { recursive: true });
  await Deno.writeTextFile(target, content);
}
console.log(`Registry JSON embeddings ${check ? 'checked' : 'generated'}.`);
