import pairs from '../../../tokens/contrast-pairs.json' with { type: 'json' };
import exclusions from '../../../tokens/contrast-exclusions.json' with { type: 'json' };
import type { TokenContrastCoverage, TokenContrastExclusion } from '../domain/contrast-contract.ts';
import { CONTROL_CONTRAST_MINIMUM, TEXT_CONTRAST_MINIMUM } from '../domain/contrast-contract.ts';

/** Load the independently reviewed pair contract, narrowing only validated AA thresholds. */
export function defaultContrastCoverage(): TokenContrastCoverage {
  if (pairs.version !== 1) throw new Error('Unknown contrast coverage version');
  return {
    decorativeRoles: pairs.decorativeRoles,
    pairs: pairs.pairs.map((pair) => {
      const minimum = pair.minimum;
      if (minimum !== TEXT_CONTRAST_MINIMUM && minimum !== CONTROL_CONTRAST_MINIMUM) {
        throw new Error(`Unsupported AA threshold: ${pair.id}`);
      }
      return { ...pair, minimum };
    }),
  };
}

/** Exclusions are checked against exact measured failures, never regenerated by the build. */
export function defaultContrastExclusions(): readonly TokenContrastExclusion[] {
  if (exclusions.version !== 1) throw new Error('Unknown contrast exclusion version');
  return exclusions.exclusions.map((exclusion) => {
    const scheme = exclusion.scheme;
    if (scheme !== 'light' && scheme !== 'dark') {
      throw new Error(`Unknown exclusion scheme: ${scheme}`);
    }
    return { ...exclusion, scheme };
  });
}
