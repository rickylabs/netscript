/** Generate the operational vocabulary from the public child health documentation. */
import { fromFileUrl, join } from '@std/path';
import { CHILD_CRASH_LOOP_THRESHOLD } from '@netscript/plugin/health';
import { z } from 'npm:zod@^4.6.5';
import {
  type GeneratedExportSurfaceEntry,
  normalizeDenoDocNode,
} from './generate-export-surface-corpus.ts';

const ROOT = fromFileUrl(new URL('../../../', import.meta.url));
const PAGE = 'docs/site/orchestration-runtime/child-health.md';
const SYMBOLS = [
  'ChildHealthState',
  'ChildHealthSnapshot',
  'ChildFatalError',
  'CHILD_CRASH_LOOP_THRESHOLD',
] as const;

const StateDeclaration = z.object({
  kind: z.literal('typeAlias'),
  def: z.object({
    tsType: z.object({
      kind: z.literal('union'),
      value: z.array(z.object({
        kind: z.literal('literal'),
        value: z.object({ kind: z.literal('string'), string: z.string() }),
      })).nonempty(),
    }),
  }),
});
const DocNode = z.object({
  symbols: z.array(z.object({ name: z.string(), declarations: z.array(z.unknown()) })),
});

/** Minimal projection of the exported type and its documentation. */
export interface ChildHealthDocumentation {
  readonly entries: readonly GeneratedExportSurfaceEntry[];
  readonly states: readonly string[];
}

/** Read the exported contract through the existing Deno documentation normalizer. */
export async function readChildHealthDocumentation(): Promise<ChildHealthDocumentation> {
  const result = await new Deno.Command(Deno.execPath(), {
    cwd: ROOT,
    args: ['doc', '--json', '--no-lock', 'packages/plugin/src/health/mod.ts'],
    stdout: 'piped',
    stderr: 'piped',
  }).output();
  if (!result.success) throw new Error(new TextDecoder().decode(result.stderr));
  const document = z.object({ nodes: z.record(z.string(), z.unknown()) }).parse(
    JSON.parse(new TextDecoder().decode(result.stdout)),
  );
  const nodes = Object.values(document.nodes);
  const symbol = nodes.flatMap((node) => DocNode.parse(node).symbols).find((symbol) =>
    symbol.name === 'ChildHealthState'
  );
  const declaration = StateDeclaration.parse(symbol?.declarations[0]);
  return {
    entries: nodes.flatMap((node) => normalizeDenoDocNode(node, '@netscript/plugin', './health')),
    states: declaration.def.tsType.value.map((member) => member.value.string),
  };
}

/** Render only documented public contract declarations; missing symbols fail closed. */
export function renderChildHealthPage({ entries, states }: ChildHealthDocumentation): string {
  const stateDocs = entries.find((entry) => entry.symbol === 'ChildHealthState')?.jsDoc ?? '';
  const documentedStates = [...stateDocs.matchAll(/^- `([^`]+)`: /gm)].map((match) => match[1]);
  if (JSON.stringify(documentedStates) !== JSON.stringify(states)) {
    throw new Error(
      'ChildHealthState descriptions must match every exported union member in order',
    );
  }
  const sections = SYMBOLS.map((symbol) => {
    const entry = entries.find((entry) => entry.symbol === symbol);
    if (!entry?.jsDoc) throw new Error(`Missing child health documentation: ${symbol}`);
    return `## \`${symbol}\`\n\n${entry.jsDoc.replaceAll('@example ', '\nExample:\n\n')}`;
  });
  return `---
layout: layouts/base.vto
title: Background child health
templateEngine: [vento, md]
---

<!-- Generated by deno task gen:child-health-docs from packages/plugin/src/domain/child-health.ts.
Edit the exported contract JSDoc, then regenerate. -->

# Background child health

The exported \`@netscript/plugin/health\` contract describes the background child that performs
durable work. Its health listener runs under the service identity, independently of an open phone,
browser, or owner session. CLI and MCP diagnostics read this same contract through the
[shared plugin health aggregate](/reference/plugin/#plugin-runtime-health-aggregation).

The exported state union contains: ${states.map((state) => `\`${state}\``).join(', ')}.

${sections.join('\n\n')}

The current threshold is **${CHILD_CRASH_LOOP_THRESHOLD.restarts} restarts within
${CHILD_CRASH_LOOP_THRESHOLD.windowMs / 1000} seconds**. The window includes its boundary.
Only \`ready\` with both readiness flags true returns HTTP 200 from \`/health\`; other states
return HTTP 503. A healthy API with a stopped or crash-looping child yields \`degraded\` in
plugin doctor and MCP health. A child-only plugin with a dead child is \`unhealthy\`.

## Authoring and migration in 0.0.8

\`declareHealthChecks\` and its unused \`HealthCheckSpec\`, \`SagasHealthCheckSpec\`, and
\`TriggersHealthCheckSpec\` types were removed. Remove those overrides and type imports from
custom Aspire contributions. Keep resource contribution and environment declarations.

The author scaffold declares the API's \`doctor.healthEndpoint\` in adapter metadata.
The generated AppHost uses the service's \`HealthCheckPath\` appsettings value, defaulting to
\`/health\`. The AppHost generator
probes enabled Deno background entries with \`RequiresKv: true\` at \`/health\`, regardless of
their resource name or entrypoint spelling. Custom children that declare this capability must
serve the shared payload. Service health paths remain metadata-driven.

See [Author a plugin](/orchestration-runtime/how-to/author-a-plugin/) for the two-tier scaffold.
Dashboard panel rendering and installed-consumer failure experiments are separate acceptance work.
`;
}

/** Format the generated page with the repository policy before checking or publishing it. */
export async function generateChildHealthPage(): Promise<string> {
  const page = renderChildHealthPage(await readChildHealthDocumentation());
  const process = new Deno.Command(Deno.execPath(), {
    cwd: ROOT,
    args: ['fmt', '--config', join(ROOT, 'deno.json'), '--ext', 'md', '-'],
    stdin: 'piped',
    stdout: 'piped',
    stderr: 'piped',
  }).spawn();
  const writer = process.stdin.getWriter();
  await writer.write(new TextEncoder().encode(page));
  await writer.close();
  const output = await process.output();
  if (!output.success) throw new Error(new TextDecoder().decode(output.stderr));
  return new TextDecoder().decode(output.stdout);
}

if (import.meta.main) {
  const page = await generateChildHealthPage();
  const path = join(ROOT, PAGE);
  if (Deno.args.includes('--check')) {
    if (await Deno.readTextFile(path) !== page) {
      throw new Error('Child health page is stale; run deno task gen:child-health-docs');
    }
    console.log('child-health-docs PASS: exported contract and vocabulary page match');
  } else {
    await Deno.writeTextFile(path, page);
    console.log(`Generated ${PAGE}`);
  }
}
