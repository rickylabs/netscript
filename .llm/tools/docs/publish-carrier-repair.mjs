/** Publish only generated output. The branch is updated by a merge commit, never a forced ref. */
export async function publishCarrierRepair({ github, context, exec }) {
  const { owner, repo } = context.repo;
  const branch = 'automation/generated-carriers';
  const output = await exec.getExecOutput('git', ['diff', '--name-only']);
  const paths = output.stdout.trim().split('\n').filter(Boolean);
  const allowed = (path) =>
    path.endsWith('.generated.ts') ||
    path === '.llm/assets/agent-docs/provenance.json' ||
    path === '.llm/tools/validation/fixtures/aspire-surface-manifest.tsv';
  if (!paths.length || paths.some((path) => !allowed(path))) {
    throw new Error('Regeneration is empty or includes non-carrier source changes.');
  }
  const main = (await github.rest.git.getCommit({ owner, repo, commit_sha: context.sha })).data;
  let previous;
  try {
    previous =
      (await github.rest.git.getRef({ owner, repo, ref: `heads/${branch}` })).data.object.sha;
  } catch (error) {
    if (error.status !== 404) throw error;
  }
  const { readFile } = await import('node:fs/promises');
  const tree = [];
  for (const path of paths) {
    const content = await readFile(path);
    const blob = await github.rest.git.createBlob({
      owner,
      repo,
      encoding: 'base64',
      content: content.toString('base64'),
    });
    tree.push({ path, mode: '100644', type: 'blob', sha: blob.data.sha });
  }
  const createdTree = await github.rest.git.createTree({
    owner,
    repo,
    base_tree: main.tree.sha,
    tree,
  });
  const parents = [...new Set([context.sha, previous].filter(Boolean))];
  const commit = await github.rest.git.createCommit({
    owner,
    repo,
    tree: createdTree.data.sha,
    parents,
    message: 'chore(tooling): regenerate merged carriers',
  });
  if (previous) {
    await github.rest.git.updateRef({
      owner,
      repo,
      ref: `heads/${branch}`,
      sha: commit.data.sha,
      force: false,
    });
  } else {await github.rest.git.createRef({
      owner,
      repo,
      ref: `refs/heads/${branch}`,
      sha: commit.data.sha,
    });}
  const title = 'chore(tooling): regenerate merged carriers';
  const body =
    '## Summary\n\nRegenerate committed carriers from the merged main source tree. Required quality checks remain unchanged.\n\n## Scope\n\nRefs #2233\n\n## Validation\n\nCarrier drift detected and regenerated by the main safety net; normal PR CI must validate this repair.\n\n## Definition of Done\n\n- [x] Only generated carriers changed\n';
  const pulls = await github.rest.pulls.list({
    owner,
    repo,
    head: `${owner}:${branch}`,
    state: 'open',
  });
  const pull = pulls.data[0]
    ? (await github.rest.pulls.update({
      owner,
      repo,
      pull_number: pulls.data[0].number,
      title,
      body,
    })).data
    : (await github.rest.pulls.create({ owner, repo, head: branch, base: 'main', title, body }))
      .data;
  const milestones = await github.paginate(github.rest.issues.listMilestones, {
    owner,
    repo,
    state: 'open',
    per_page: 100,
  });
  const milestone = milestones.find((item) => item.title === '0.0.8')?.number;
  if (!milestone) throw new Error('Required milestone 0.0.8 is missing.');
  await github.rest.issues.update({
    owner,
    repo,
    issue_number: pull.number,
    milestone,
    labels: ['type:chore', 'area:tooling', 'priority:p1', 'status:impl-eval'],
  });
}
