/** Regenerate reviewed 0.0.8 source hunks; never infer edits from a moving registry at runtime. */
import { basename } from '@std/path';

const base = Deno.args[0];
if (!base || !/^[a-f0-9]{40}$/.test(base)) throw new Error('Supply the exact 0.0.8 source commit.');
const result = await new Deno.Command('git', {
  args: ['diff', '--no-ext-diff', '--unified=3', base, '--', 'packages/fresh-ui/registry'],
  stdout: 'piped',
  stderr: 'piped',
}).output();
if (!result.success) throw new Error(new TextDecoder().decode(result.stderr));
const files: { file: string; edits: { before: string; after: string }[] }[] = [];
let current: typeof files[number] | undefined;
let edit: { before: string; after: string } | undefined;
for (const line of new TextDecoder().decode(result.stdout).split('\n')) {
  if (line.startsWith('diff --git ')) {
    current = undefined;
    edit = undefined;
  } else if (line.startsWith('+++ b/')) {
    const path = line.slice(6);
    if (!/\.tsx(?:\.template)?$/.test(path)) continue;
    current = { file: basename(path).replace(/\.template$/, ''), edits: [] };
    files.push(current);
  } else if (line.startsWith('@@ ') && current) {
    edit = { before: '', after: '' };
    current.edits.push(edit);
  } else if (edit && /^[ +\-]/.test(line)) {
    if (line[0] !== '+') edit.before += line.slice(1) + '\n';
    if (line[0] !== '-') edit.after += line.slice(1) + '\n';
  }
}
const directory = new URL(
  '../../packages/cli/src/public/features/ui/migrate/data/',
  import.meta.url,
);
await Deno.mkdir(directory, { recursive: true });
// Category-sized modules remain reviewable and below the doctrine file limit.
const imports: string[] = [];
for (let offset = 0; offset < files.length; offset += 10) {
  const number = offset / 10 + 1;
  const name = `variants${number}`;
  const source = `// @generated by .llm/tools/generate-ui-variant-migration.ts from ${base}\n` +
    `import type { VariantFileMigration } from '../variant-migration-contract.ts';\n` +
    `export const ${name}: readonly VariantFileMigration[] = ${
      JSON.stringify(files.slice(offset, offset + 10), null, 2)
    };\n`;
  await Deno.writeTextFile(new URL(`${number}.ts`, directory), source);
  imports.push(`import { ${name} } from './data/${number}.ts';`);
}
await Deno.writeTextFile(
  new URL('../variant-migration-data.ts', directory),
  `// @generated by .llm/tools/generate-ui-variant-migration.ts\n` + imports.join('\n') +
    `\nexport const variantMigrations = [${
      imports.map((_, i) => `...variants${i + 1}`).join(', ')
    }];\n`,
);
const formatting = await new Deno.Command('deno', {
  args: ['fmt', '--no-config', '--single-quote', '--line-width', '100',
    ...Array.from({length: imports.length}, (_, i) => new URL(`${i + 1}.ts`, directory).pathname),
    new URL('../variant-migration-data.ts', directory).pathname],
  stdout: 'null', stderr: 'piped',
}).output();
if (!formatting.success) throw new Error(new TextDecoder().decode(formatting.stderr));
console.log(`Recorded ${files.length} versioned source migrations.`);
